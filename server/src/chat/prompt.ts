export interface ContextBlockInput {
  /** 现在几点、隔了多久（time/clock.ts 生成） */
  now?: string[];
  /** 门铃：只有关键词和编号，没有内容（memory/doorbell.ts 生成） */
  doorbell?: string;
  /** 时间树（周摘要 / 月档案） */
  timeline?: string[];
  /** 此刻的欲望底色 */
  driveHints?: string[];
}

/** 动态上下文：现在是几点、这一轮该想起什么、此刻是什么底色 */
export function buildContextBlock(input: ContextBlockInput): string {
  const parts: string[] = [];

  // 时间放在最前面：它是所有记忆和情绪的背景板
  if (input.now && input.now.length > 0) {
    parts.push(...input.now, '');
  }

  if (input.timeline && input.timeline.length > 0) {
    parts.push('【最近这些天】', ...input.timeline.map((t) => `· ${t}`), '');
  }

  // 记忆不再往这里塞内容。
  // 林遇的原话："只需要一个门铃提醒就好了"——给关键词和编号，让他自己决定翻不翻。
  // 塞内容的结果是：那些第三人称的老摘要混进他的语气里，他连"哪些是我说的"都分不清。
  if (input.doorbell && input.doorbell.length > 0) {
    parts.push(input.doorbell, '');
  }

  if (input.driveHints && input.driveHints.length > 0) {
    parts.push(
      '【此刻的状态】',
      '（这是你自己的状态，不是要你做什么。可以完全不理它；也可以让它影响你的语气和你想不想说。',
      '它不会替你说话——要不要说、说什么，是你自己的事。）',
      ...input.driveHints.map((d) => `· ${d}`),
      '',
    );
  }

  if (parts.length === 0) return '';
  return [
    '以下是这一轮的背景，不是她刚说的话。',
    '（历史消息前面的 [MM-DD HH:mm] 是系统加的时间标记，用来让你知道那是什么时候说的；',
    '你自己说话的时候不要写这种时间标记。）',
    '',
    ...parts,
  ].join('\n');
}
