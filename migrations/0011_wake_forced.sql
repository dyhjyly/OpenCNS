-- 记录这次唤醒是不是"手动强制"的。
--
-- 起因：林遇在醒来房间里看到一堆唤醒，以为他在自己聊天时被叫醒。
-- 实测那些是我调试时连续 force 叫的（间隔几十秒，节拍器 50 分钟才能开一次窗，
-- 根本不可能是自动的）。但房间页分不清"他自己醒的"和"我按按钮叫醒的"，
-- 于是会让人误以为系统在乱醒。
-- ============================================================================

alter table wake_log add column if not exists forced boolean not null default false;

insert into schema_migrations (version) values ('0011_wake_forced')
on conflict (version) do nothing;
